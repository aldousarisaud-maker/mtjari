const dict: Record<Locale, Record<Key, string>> = { ar, en };

export function t(locale: Locale, key: Key): string {
  return dict[locale][key];
}

export function errorText(locale: Locale, code: string | undefined): string {
  const key = `err.${code}` as Key;
  return key in dict[locale] ? dict[locale][key] : dict[locale]['err.generic'];
}

const ROLE_AR: Record<string, string> = { owner: 'المالك', admin: 'مدير', manager: 'مدير المتجر', staff: 'موظف', viewer: 'مشاهد' };
const STATUS_AR: Record<string, string> = { DRAFT: 'مسودة', ACTIVE: 'نشط', SUSPENDED: 'موقوف', CLOSED: 'مغلق' };

/** Built-in roles are translated; custom roles keep the name the merchant gave them. */
export function roleLabel(locale: Locale, role: { key?: string | null; name: string }): string {
  return locale === 'ar' && role.key && ROLE_AR[role.key] ? ROLE_AR[role.key]! : role.name;
}

export function statusLabel(locale: Locale, status: string): string {
  return locale === 'ar' ? (STATUS_AR[status] ?? status) : status.charAt(0) + status.slice(1).toLowerCase();
}
