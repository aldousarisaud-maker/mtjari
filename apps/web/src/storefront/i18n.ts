export type SfKey = keyof typeof ar;
const dict = { ar, en };
export const sfLocales = ['ar', 'en'] as const;
export const isSfLocale = (v: string | undefined): v is Locale => v === 'ar' || v === 'en';
export const st = (l: Locale, key: SfKey) => dict[l][key];
export const sfError = (l: Locale, code: string | undefined) => {
  const key = `err.${code}` as SfKey;
  return key in dict[l] ? dict[l][key] : dict[l]['err.generic'];
};
/** Text in the shopper's language, falling back to the other one the merchant filled in. */
export const pick = (l: Locale, x: { nameAr: string | null; nameEn: string | null }) => (l === 'ar' ? x.nameAr || x.nameEn : x.nameEn || x.nameAr) ?? '';
export const pickText = (l: Locale, ar_: string | null | undefined, en_: string | null | undefined) => (l === 'ar' ? ar_ || en_ : en_ || ar_) ?? '';
